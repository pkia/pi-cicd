def test_default_state_expands_home(tmp_path):
    """The default state is `~/.local/state/...` — Path does not expand `~`,
    so an unexpanded default writes a literal `~` directory beside the cwd
    (found by the first live run). HOME decides where it really lands."""
    home = tmp_path / "home"
    cwd = tmp_path / "cwd"
    home.mkdir(), cwd.mkdir()
    with Sink() as sink:
        conf, env, _ = write_env(tmp_path, sink.url, host=HEALTHY_HOST)
        env["HOME"] = str(home)
        proc = subprocess.run([str(TOOL), "--config", str(conf)], env=env,
                              cwd=str(cwd), stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE, text=True, timeout=120,
                              check=False)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    landed = home / ".local" / "state" / "dns-watch" / "state.json"
    assert landed.is_file()
    assert read_state(landed)["status"] == "healthy"
    assert not (cwd / "~").exists()


def test_probe_resolves_beside_the_script_when_not_on_path(tmp_path):
    """CI has no ~/.local/bin and no installed dns-check: with PATH stripped
    of it, the copy shipped beside dns-watch must be the one that runs."""
    with Sink() as sink:
        conf, env, _ = write_env(tmp_path, sink.url, host=BROKEN_HOST)
        env["PATH"] = "/usr/bin:/bin"          # curl/getent live here
        proc = subprocess.run([str(TOOL), "--config", str(conf),
                               "--state", str(tmp_path / "s.json"), "-v"],
                              env=env, cwd=str(tmp_path),
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              text=True, timeout=120, check=False)
    assert proc.returncode == 1, proc.stdout + proc.stderr
    assert len(sink.posts) == 1
    assert str(PROBE) in proc.stderr      # the resolved path is named -v


# -------------------------------------------------------------- read-only

BANNED = ("tee", "sed -i", "mv ", "cp ", "rm ", "touch ", "truncate",
          "systemctl ", "nmcli connection up", "nmcli connection modify",
          "nmcli connection down", "install ")


def test_probe_source_is_read_only():
    """The written rule: after dropping comment lines and lines that only
    print (echo/printf — where the recovery commands live), and ignoring
    redirections to /dev/null (which land nowhere), no line writes a file
    or acts on the system. This is the source half of the acceptance."""
    source = PROBE.read_text(encoding="utf-8")
    offenders = []
    for number, raw in enumerate(source.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        body = line
        for harmless in ("2>/dev/null", "2>&1", ">/dev/null"):
            body = body.replace(harmless, "")
        if re.match(r"^(echo|printf)\b", body):
            continue
        if ">" in body:
            offenders.append((number, line, "redirection"))
        for verb in BANNED:
            if verb in body:
                offenders.append((number, line, verb))
    assert offenders == [], offenders


def snapshot(tree):
    """rel path -> (size, mtime_ns, sha256) for every file under tree."""
    out = {}
    for path in sorted(Path(tree).rglob("*")):
        if ".git" in path.parts or "__pycache__" in path.parts:
            continue
        rel = str(path.relative_to(tree))
        if path.is_dir():
            out[rel] = ("dir",)
            continue
        data = path.read_bytes()
        out[rel] = (len(data), path.stat().st_mtime_ns,
                    hashlib.sha256(data).hexdigest())
    return out


def copy_repo(tmp_path):
    dest = tmp_path / "tree"
    shutil.copytree(REPO, dest, ignore=shutil.ignore_patterns(
        ".git", "__pycache__", "*.pyc"))
    return dest


def test_probe_run_leaves_tree_byte_identical(tmp_path):
    tree = copy_repo(tmp_path)
    before = snapshot(tree)
    conf, env = tmp_path / "conf", dict(os.environ)
    env.update({"DNS_CHECK_URL": "http://127.0.0.1:9/",
                "DNS_CHECK_HOST": HEALTHY_HOST, "DNS_CHECK_TIMEOUT": "2",
                "DNS_CHECK_RESOLV_CONF": str(tmp_path / "resolv.conf")})
    (tmp_path / "resolv.conf").write_text(HEADER_ONLY, encoding="utf-8")
    proc = subprocess.run([str(tree / "dns-check")], env=env, cwd=str(tree),
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          text=True, timeout=120, check=False)
    assert proc.returncode == 2, proc.stdout + proc.stderr   # egress-only fault
    assert snapshot(tree) == before


def test_watch_run_writes_only_its_state(tmp_path):
    tree = copy_repo(tmp_path)
    before = snapshot(tree)
    with Sink() as sink:
        conf, env, _ = write_env(tmp_path, sink.url, host=HEALTHY_HOST)
        state = tmp_path / "state.json"
        proc = subprocess.run([str(tree / "dns-watch"), "--config", str(conf),
                               "--state", str(state)], env=env, cwd=str(tree),
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              text=True, timeout=120, check=False)
        assert proc.returncode == 0, proc.stdout + proc.stderr
        assert sink.posts == []
    assert snapshot(tree) == before
    assert not str(state).startswith(str(tree))
    assert Path(state).is_file()
