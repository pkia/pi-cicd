"""dns-watch — the timer half of dns-check, proven by execution.

Every test drives the real CLIs in a subprocess: dns-watch as the unit
runs it, dns-check with its own documented env overrides (DNS_CHECK_URL,
DNS_CHECK_HOST, DNS_CHECK_TIMEOUT, DNS_CHECK_RESOLV_CONF), and a local
HTTP sink standing in for ntfy. Nothing here touches the network beyond
loopback, and nothing writes outside tmp_path.

The acceptance pair from the board row lives in
test_first_broken_run_pages_once / test_five_more_broken_runs_stay_silent
/ test_recovery_pages_once, and the read-only half in
test_probe_source_is_read_only + test_probe_run_leaves_tree_byte_identical.
"""

import hashlib
import json
import os
import re
import shutil
import subprocess
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
TOOL = REPO / "dns-watch"
PROBE = REPO / "dns-check"

pytestmark = pytest.mark.skipif(
    shutil.which("curl") is None or shutil.which("getent") is None,
    reason="dns-check needs curl and getent",
)

# A header-only /etc/resolv.conf — the exact 2026-11-16 shape.
HEADER_ONLY = "# Generated by NetworkManager\n"
WITH_NAMESERVERS = "# Generated by NetworkManager\nnameserver 1.1.1.1\n"

BROKEN_HOST = "nope.invalid"          # reserved TLD: must never resolve
HEALTHY_HOST = "localhost"            # in /etc/hosts on any real box


class Sink:
    """One loopback HTTP server standing in for the ntfy root endpoint."""

    def __init__(self):
        self.posts = []
        outer = self

        class Handler(BaseHTTPRequestHandler):
            def do_POST(self):                       # noqa: N802
                length = int(self.headers.get("Content-Length") or 0)
                body = self.rfile.read(length).decode("utf-8", "replace")
                try:
                    outer.posts.append(json.loads(body))
                except ValueError:
                    outer.posts.append({"raw": body})
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(b"{}")
                outer.paths.append(self.path)
                outer.headers.append(dict(self.headers))

            def do_GET(self):                        # noqa: N802
                # The raw-IP probe: 200 means "egress works".
                self.send_response(200)
                self.send_header("Content-Length", "2")
                self.end_headers()
                self.wfile.write(b"ok")

            def log_message(self, *args):            # keep pytest output clean
                pass

        self.paths = []
        self.headers = []
        self.server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self.thread = threading.Thread(target=self.server.serve_forever,
                                       daemon=True)

    def __enter__(self):
        self.thread.start()
        return self

    def __exit__(self, *exc):
        self.server.shutdown()
        self.server.server_close()
        self.thread.join(timeout=5)
        return False

    @property
    def url(self):
        host, port = self.server.server_address[:2]
        return f"http://{host}:{port}"


def write_env(tmp_path, sink_url, *, host, resolv=HEADER_ONLY,
              probe_url=None, extra="", dns_check=None):
    """Config file + env for one dns-watch run, both inside tmp_path."""
    conf = tmp_path / "dns-watch.conf"
    lines = [f"NTFY_URL={sink_url}", "NTFY_TOKEN=drill-token",
             "NTFY_TOPIC=drill", "TIMEOUT_SECS=5"]
    if dns_check:
        lines.append(f"DNS_CHECK={dns_check}")
    if extra:
        lines.append(extra)
    conf.write_text("\n".join(lines) + "\n", encoding="utf-8")
    resolv_file = tmp_path / "resolv.conf"
    resolv_file.write_text(resolv, encoding="utf-8")
    env = dict(os.environ)
    env.update({
        "DNS_CHECK_URL": probe_url or (sink_url + "/ip"),
        "DNS_CHECK_HOST": host,
        "DNS_CHECK_TIMEOUT": "3",
        "DNS_CHECK_RESOLV_CONF": str(resolv_file),
        # The box's real mute file must never silence a test run.
        "NTFY_MUTE_FILE": str(tmp_path / "no-such-mute"),
    })
    return conf, env, resolv_file


def run_tool(tmp_path, sink_url, *, host=HEALTHY_HOST, state=None,
             dry_run=False, resolv=HEADER_ONLY, probe_url=None,
             dns_check=None, cwd=None):
    conf, env, resolv_file = write_env(
        tmp_path, sink_url, host=host, resolv=resolv,
        probe_url=probe_url, dns_check=dns_check)
    state = state or (tmp_path / "state.json")
    argv = [str(TOOL), "--config", str(conf), "--state", str(state), "-v"]
    if dry_run:
        argv.append("--dry-run")
    proc = subprocess.run(argv, env=env, cwd=str(cwd or REPO),
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          text=True, timeout=120, check=False)
    return proc, state, resolv_file


def read_state(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


# ---------------------------------------------------------------- paging

def test_first_broken_run_pages_once(tmp_path):
    with Sink() as sink:
        proc, state, resolv_file = run_tool(tmp_path, sink.url, host=BROKEN_HOST)
        assert proc.returncode == 1, proc.stdout + proc.stderr
        assert len(sink.posts) == 1
        post = sink.posts[0]
        assert post["topic"] == "drill"
        assert "DNS BROKEN" in post["title"]
        # The page names the file that caused it, not just "DNS is down".
        assert str(resolv_file) in post["message"]
        assert "header-only" in post["message"]
        assert "VERDICT: DNS CONFIG BROKEN" in post["message"]
        # The page is authenticated, like every other publisher here.
        assert sink.headers[0]["Authorization"] == "Bearer drill-token"
        record = read_state(state)
        assert record["status"] == "dns"
        assert record["exit_code"] == 1
        assert record["pages"] == 1
        assert record["since"]


def test_five_more_broken_runs_stay_silent(tmp_path):
    with Sink() as sink:
        proc, state, _ = run_tool(tmp_path, sink.url, host=BROKEN_HOST)
        assert proc.returncode == 1
        first_since = read_state(state)["since"]
        for _ in range(5):
            proc, state, _ = run_tool(tmp_path, sink.url, host=BROKEN_HOST)
            assert proc.returncode == 1
        assert len(sink.posts) == 1, [p["title"] for p in sink.posts]
        record = read_state(state)
        assert record["pages"] == 1
        # A standing failure stays one event: its `since` does not move.
        assert record["since"] == first_since
        assert "silent" in proc.stderr


def test_recovery_pages_once(tmp_path):
    with Sink() as sink:
        run_tool(tmp_path, sink.url, host=BROKEN_HOST)
        proc, state, _ = run_tool(tmp_path, sink.url, host=HEALTHY_HOST)
        assert proc.returncode == 0, proc.stdout + proc.stderr
        assert len(sink.posts) == 2
        assert "healthy" in sink.posts[1]["title"]
        assert "Back to healthy" in sink.posts[1]["message"]
        # And then quiet again.
        proc, state, _ = run_tool(tmp_path, sink.url, host=HEALTHY_HOST)
        assert len(sink.posts) == 2
        assert read_state(state)["status"] == "healthy"


def test_first_healthy_run_is_silent(tmp_path):
    with Sink() as sink:
        proc, state, _ = run_tool(tmp_path, sink.url, host=HEALTHY_HOST)
        assert proc.returncode == 0
        assert sink.posts == []
        record = read_state(state)
        assert record["status"] == "healthy"
        assert record["pages"] == 0


def test_alternation_pages_every_change(tmp_path):
    with Sink() as sink:
        for host, rc in ((BROKEN_HOST, 1), (HEALTHY_HOST, 0),
                         (BROKEN_HOST, 1), (HEALTHY_HOST, 0)):
            proc, _, _ = run_tool(tmp_path, sink.url, host=host)
            assert proc.returncode == rc, proc.stdout + proc.stderr
        assert len(sink.posts) == 4
        titles = [p["title"] for p in sink.posts]
        assert "DNS BROKEN" in titles[0]
        assert "healthy" in titles[1]
        assert "DNS BROKEN" in titles[2]
        assert "healthy" in titles[3]


def test_egress_failure_is_named_separately(tmp_path):
    """Names resolve, the raw-IP probe fails -> exit 2, its own title."""
    with Sink() as sink:
        proc, state, _ = run_tool(tmp_path, sink.url, host=HEALTHY_HOST,
                                  probe_url="http://127.0.0.1:1/")
        assert proc.returncode == 2, proc.stdout + proc.stderr
        assert len(sink.posts) == 1
        assert "EGRESS BROKEN" in sink.posts[0]["title"]
        assert "odd" in sink.posts[0]["message"]
        assert read_state(state)["status"] == "egress"


def test_dry_run_publishes_and_writes_nothing(tmp_path):
    with Sink() as sink:
        proc, state, _ = run_tool(tmp_path, sink.url, host=BROKEN_HOST,
                                  dry_run=True)
        assert proc.returncode == 1
        assert sink.posts == []
        assert not Path(state).exists()
        assert "would page" in proc.stdout


